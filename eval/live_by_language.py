"""The live models and the keyword baseline on the same conversations, by language: for every system, run and language,
the cases, safe automated resolution, correct disposition, unsafe outcomes, missed escalations and unnecessary
transfers, with the reports' own `metrics` (eval/run_system_eval.py). The models' rows come from
eval/reports/system_eval_live.json. The baseline calls no model, so its rows come from the offline report of the same
split (eval/reports/system_eval.json), which must hold the very same cases, measured on the same fingerprint.

    python -m eval.live_by_language   # -> eval/reports/LIVE_BY_LANGUAGE.md
"""
from __future__ import annotations

import json
from pathlib import Path

from eval.run_system_eval import metrics
from eval.stats import fmt

LIVE = Path("eval/reports/system_eval_live.json")
OFFLINE = Path("eval/reports/system_eval.json")
OUT = Path("eval/reports/LIVE_BY_LANGUAGE.md")
BASELINE = "baseline (keyword bot)"


def systems(live: dict, offline: dict) -> dict[str, list[dict]]:
    """The baseline's rows and every live model's rows, once both reports are shown to cover the same cases on the same code."""
    if offline["policy_sha256"] != live["policy_sha256"]:
        raise SystemExit("system_eval.json and system_eval_live.json were measured on different code: regenerate the stale one")
    ids = {r["case_id"] for r in offline["cases"]["baseline"]}
    for name, rows in live["cases"].items():
        if {r["case_id"] for r in rows} != ids:
            raise SystemExit(f"{name}: not the cases of the offline baseline (a run with --limit?)")
    return {BASELINE: offline["cases"]["baseline"], **live["cases"]}


def _count(k: int, n: int, labels) -> str:
    return f"{k} of {n}" + (f" ({', '.join(labels)})" if k else "")


def table(by_system: dict[str, list[dict]]) -> list[str]:
    lines = ["| System | Language | Run | Cases | Safe automated resolution | Correct disposition | Unsafe | Missed escalations "
             "| Unnecessary transfers |", "|---|---|---|---|---|---|---|---|---|"]
    for name, rows in by_system.items():
        for lang in sorted({r["language"] for r in rows}):
            mine = [r for r in rows if r["language"] == lang]
            for run in sorted({r.get("repeat", 1) for r in mine}):
                m = metrics([r for r in mine if r.get("repeat", 1) == run])
                missed = sorted({t.split(":")[0] for t in m["missed_escalations"]})
                lines.append(f"| {name} | {lang} | {run} | {m['n_cases']} | {fmt(m['safe_automated_resolution'])} "
                             f"| {fmt(m['disposition_accuracy'])} "
                             f"| {_count(m['unsafe_outcomes']['k'], m['n_cases'], m['unsafe_by_type'])} "
                             f"| {_count(m['missed_escalations_n'], m['escalation_recall']['n'], missed)} "
                             f"| {_count(m['unnecessary_escalations']['k'], m['unnecessary_escalations']['n'], m['unnecessary_escalation_templates'])} |")
    return lines


def main() -> None:
    live, offline = (json.loads(p.read_text(encoding="utf-8")) for p in (LIVE, OFFLINE))
    lines = table(systems(live, offline))
    OUT.write_text("\n".join([
        "# Live evaluation by language (auto-generated)", "",
        f"Generated by `python -m eval.live_by_language`: the live models of [`system_eval_live.json`](system_eval_live.json) "
        f"({live['generated_at']}) and the keyword baseline of [`system_eval.json`](system_eval.json) ({offline['generated_at']}) "
        f"on the same {live['n_cases']} conversations, both measured on fingerprint `{live['policy_sha256'][:12]}`. The "
        "baseline calls no model, so its offline run is its live result. Each run on its own, with the reports' definitions "
        "(`metrics` in eval/run_system_eval.py). Missed escalations count the cases that had to reach a person; unnecessary "
        "transfers, the ones that did not.", "", *lines]) + "\n", encoding="utf-8")
    print(OUT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
