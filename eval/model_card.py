"""The intent classifier's model card: what it is for, what it was trained and scored on, how it does, and where it fails.

    python -m eval.model_card        # writes docs/MODEL_CARD.md

The prose is ours; every figure is read from the versioned reports (eval/reports/intent_classifier.json,
docs/evidence/model_study.json, eval/models/intent_clf_meta.json), so a number in the card cannot drift from the report.
tests/test_model_card.py holds the committed card to a fresh render.
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

REPORT = Path("eval/reports/intent_classifier.json")
STUDY = Path("docs/evidence/model_study.json")
META = Path("eval/models/intent_clf_meta.json")
OUT = Path("docs/MODEL_CARD.md")


def pct(r: dict) -> str:
    """A rate with its 95% interval and denominator, the form every report in this repository uses."""
    return f"{r['rate']:.1%} [{r['ci95'][0]:.1%}-{r['ci95'][1]:.1%}] (n={r['n']})"


def render(report: dict, study: dict, meta: dict) -> str:
    t = report["test"]
    learned, kw = t["learned"], t["baseline_keywords"]
    guard = t["escalation_guard"]
    runtime = guard["lexicon_or_classifier (runtime)"]
    pair = t["paired_vs_keywords"]
    lang = learned["by_language"]
    shipped = next(c for c in study["sensitivity"] if c["shipped"])
    other = [c for c in study["sensitivity"] if not c["shipped"]]
    last = study["learning_curve"][-1]
    before = study["learning_curve"][-2]
    pc = learned["per_class"]
    L = ["# Model card: intent classifier", "",
         f"Generated by `python -m eval.model_card` from `eval/reports/intent_classifier.json` (run {report['generated_at'][:19]}) and "
         f"`docs/evidence/model_study.json` (run {study['generated_at'][:19]}). Every figure below is read from those reports.", "",
         "## What it is", "",
         f"A TF-IDF text classifier ({report['chosen_variant']} features: character 2-5-grams and word 1-2-grams) with a logistic regression "
         f"(C = {study['shipped']['C']:g}, balanced class weights), trained with scikit-learn {report['versions']['sklearn']} on {report['train_n']} utterances. "
         "It labels a customer's message as one of six intents: `balance_inquiry`, `transaction_lookup`, `payment_status`, `exchange_rate_inquiry`, `out_of_scope` or `requires_escalation`.", "",
         "## What it is used for, and what it must not be used for", "",
         "At runtime it does two things before or around the language model (`agent/policy/intent_guard.py`), both deterministic given the model file:", "",
         f"1. **Escalation guard.** A message is handed to a person if the keyword lexicon fires **or** the probability of `requires_escalation` is at least {meta['escalation_threshold']} "
         "(a threshold chosen on dev for recall with false escalations at most 5%, never on test).",
         "2. **Abstain or clarify.** When the model answers without calling a tool, its `out_of_scope` reading decides whether the reply is a refusal or a clarifying question.", "",
         "It **does not decide outcomes, authorize actions or detect fraud.** Eligibility, routing and every side effect are code (`docs/decisions/ADR-001-model-interprets-code-speaks.md`, "
         "`docs/decisions/ADR-002-one-action-confirmed-in-code.md`). Using it as a fraud or risk score would be wrong: the fraud labels hold no learnable signal "
         "(`docs/decisions/ADR-005-no-fraud-or-risk-model.md`). If the model file is missing, both jobs fall back to keywords and the degradation is logged.", "",
         "## Data", "",
         f"- **Training:** {report['train_n']} utterances written by the team from templates (`eval/test_cases/intent_dataset.csv`, sha256 `{report['versions']['train_sha256'][:12]}`). "
         "The keyword baseline's rules were written from the same templates.",
         f"- **Held-out:** {report['heldout_n']} utterances written after the training data and the baseline were frozen, with deliberately different phrasing (regional slang, abbreviations, no accents, code-switching), "
         f"plus 2 real request sentences from the dataset's transcripts. Split by a fixed hash into dev ({report['dev_n']}, used for selection and the threshold) and test ({report['test_n']}, scored once). "
         f"Phrases too close to the training text were left out by a leakage check.",
         "- **No real customer text.** The organizer's transcripts hold 42 distinct customer texts (`docs/data_quality.md`), so every training and evaluation utterance except 2 was written by the team. "
         "We have no record of a native-speaker review of the Portuguese text.", "",
         "## How it does (test split, scored once)", "",
         "| | Keyword baseline | Learned |", "|---|---|---|",
         f"| Accuracy | {pct(kw['accuracy'])} | {pct(learned['accuracy'])} |",
         f"| Macro-F1 | {kw['macro_f1']:.4f} | {learned['macro_f1']:.4f} |", "",
         f"On the same {pair['n']} utterances the learned classifier is right where the baseline is wrong on {pair['only_b_right']} and the reverse on {pair['only_a_right']}: "
         f"{pair['diff'] * 100:+.1f} points (paired bootstrap 95% [{pair['diff_ci95'][0] * 100:+.1f}, {pair['diff_ci95'][1] * 100:+.1f}], exact McNemar p = {pair['mcnemar_p']}).", "",
         "**Escalation guard** (what actually runs before the model):", "",
         "| Guard | Recall on `requires_escalation` | False escalations on the rest |", "|---|---|---|"]
    for name in ("lexicon_only", "classifier_only", "lexicon_or_classifier (runtime)"):
        g = guard[name]
        L.append(f"| {name} | {pct(g['recall'])} | {pct(g['false_escalation'])} |")
    L += ["", f"The runtime guard missed {runtime['missed']} of {runtime['recall']['n']} required escalations on test. A miss is a real missed escalation: the language model has no escalate tool "
          "(`eval/reports/intent_classifier.md` names the miss).", "",
          "## Where it fails", "",
          f"- **Escalation is the weakest class on its own.** `requires_escalation` recall is {pct(pc['requires_escalation']['recall'])} for the classifier alone, which is why it is only ever used together with the lexicon.",
          f"- **Out of scope** recall is {pct(pc['out_of_scope']['recall'])}: the baseline does better there, and some out-of-scope requests are read as another intent.",
          f"- **Portuguese is behind Spanish:** {pct(lang['pt'])} against {pct(lang['es'])}. The intervals overlap, so this is a gap we cannot prove and cannot rule out, and we have not separated its cause.",
          f"- **Slang:** {pct(learned['by_style']['slang'])}. Three utterances: read it as a warning, not a rate.",
          "- **Scored on text the team wrote.** Shared phrasing habits between training and held-out text can flatter both systems, so the figures are a ceiling for how it reads real customers, not an estimate of it.", "",
          "## How much its design choices matter", "",
          f"A sensitivity study on dev only (`docs/evidence/model_study.md`, protocol fixed before it ran: the shipped model does not change). Of the {len(other)} other representation and regularization settings, "
          f"{sum(c['distinguishable_from_shipped'] for c in other)} are distinguishably worse than the shipped one on dev macro-F1 ({shipped['dev_macro_f1']:.4f}) and the rest are within noise; none is better. "
          f"The shipped configuration was chosen on that same dev set, so its row is the optimistic one. The learning curve is "
          + ("still rising at the end" if last["dev_macro_f1_mean"] > before["dev_macro_f1_max"] else "flat at the end")
          + f" ({before['dev_macro_f1_mean']:.4f} at {round(100 * before['fraction'])}% of the data, {last['dev_macro_f1_mean']:.4f} at {round(100 * last['fraction'])}%), "
          "which says that more text of the same kind, ideally written by people outside the team, is the lever.", "",
          "## Reproducing it", "",
          "- `make train-eval` rebuilds the dataset, trains, selects on dev and scores test once; it writes `eval/reports/intent_classifier.{md,json}` and the model.",
          "- `python -m eval.model_study` re-runs the sensitivity study; `python -m eval.model_card` re-renders this card.",
          "- With `requirements-tracking.txt` installed, every selection and evaluation run is also logged to MLflow (`make mlflow-ui`); the store is local and git-ignored.",
          "- `make validate-data-ml` checks the data contracts, the split and the leakage controls as PASS/FAIL.", ""]
    return "\n".join(L)


def main() -> None:
    card = render(*(json.loads(p.read_text(encoding="utf-8")) for p in (REPORT, STUDY, META)))
    OUT.write_text(card, encoding="utf-8")
    print(f"wrote {OUT} ({len(card.splitlines())} lines, {datetime.now(timezone.utc):%Y-%m-%d})")


if __name__ == "__main__":
    main()
